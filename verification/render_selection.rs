use crate::install_selection::{channel, selection, Override, Selection};
use vstd::prelude::*;

verus! {

#[derive(Clone, Copy)]
enum Retention { None, Reports, Native, Both }

fn retention(reports: bool, native: bool) -> (out: Retention)
    ensures
        (out is Reports) == (reports && !native),
        (out is Native) == (!reports && native),
        (out is Both) == (reports && native),
        (out is None) == (!reports && !native),
{
    match (reports, native) {
        (false, false) => Retention::None,
        (true, false) => Retention::Reports,
        (false, true) => Retention::Native,
        (true, true) => Retention::Both,
    }
}

fn include_setup(features: bool, check: bool, reports: bool, native: bool) -> (out: bool)
    ensures out == (features || check || reports || native),
{
    features || check || !matches!(retention(reports, native), Retention::None)
}

fn include_tool(from_features: bool, report_runner: bool, native_bootstrap: bool) -> (out: bool)
    ensures out == (from_features || report_runner || native_bootstrap),
{
    from_features || report_runner || native_bootstrap
}

fn accepts_repository(pr: bool, supplied: bool, owner_and_name: bool) -> (out: bool)
    ensures out == ((!pr && !supplied) || owner_and_name),
{
    !pr && !supplied || owner_and_name
}

fn accepts_channel(pinned_allowed: bool, pinned: bool, named: bool, exact: bool) -> (out: bool)
    ensures out == ((pinned_allowed && pinned) || named || exact),
{
    matches!(channel(pinned_allowed && pinned || named, true, exact), Override::Use)
}

fn accepts_override(selected: bool, organization: bool, valid: bool) -> (out: bool)
    ensures out == (selected && organization && valid),
{
    selected && organization && valid
}

fn effective_channel(has_override: bool) -> (out: bool)
    ensures out == has_override,
{
    matches!(selection(false, has_override), Selection::Override)
}

fn boundary_expectations() {
    let both = retention(true, true);
    let native = retention(false, true);
    assert(both is Both && native is Native);
    let observed = include_setup(false, false, false, false);
    assert(!observed);
    let observed = include_setup(false, true, false, false);
    assert(observed);
    let observed = include_setup(false, false, true, false);
    assert(observed);
    let observed = include_setup(false, false, false, true);
    assert(observed);
    let observed = include_tool(true, true, false);
    assert(observed);
    let observed = include_tool(false, false, true);
    assert(observed);
    let observed = include_tool(false, false, false);
    assert(!observed);
    let observed = accepts_repository(false, false, false);
    assert(observed);
    let observed = accepts_repository(true, false, false);
    assert(!observed);
    let observed = accepts_repository(false, true, false);
    assert(!observed);
    let observed = accepts_repository(true, true, true);
    assert(observed);
    let observed = accepts_channel(true, true, false, false);
    assert(observed);
    let observed = accepts_channel(false, true, false, false);
    assert(!observed);
    let observed = accepts_channel(false, false, true, false);
    assert(observed);
    let observed = accepts_channel(false, false, false, true);
    assert(observed);
    let observed = accepts_channel(true, false, false, false);
    assert(!observed);
    let observed = accepts_override(false, true, true);
    assert(!observed);
    let observed = accepts_override(true, false, true);
    assert(!observed);
    let observed = accepts_override(true, true, false);
    assert(!observed);
    let observed = accepts_override(true, true, true);
    assert(observed);
    let inherited = effective_channel(false);
    let overridden = effective_channel(true);
    assert(!inherited && overridden);
}

} // verus!

#[verifier::external]
fn table<const N: usize>(name: &str, value: impl Fn([bool; N]) -> String) {
    println!("{{%- set {name} = {{");
    for index in 0..(1 << N) {
        let inputs = std::array::from_fn(|bit| index & (1 << (N - bit - 1)) != 0);
        let keys = inputs.map(|flag| if flag { "true" } else { "false" });
        println!("    ({}{}): {},", keys.join(", "), if N == 1 { "," } else { "" }, value(inputs));
    }
    println!("}} -%}}");
}

#[verifier::external]
pub fn emit() {
    boundary_expectations();
    println!("{{# Generated by verification/render_selection.rs. #}}");
    table("setup", |[features, check, reports, native]| {
        include_setup(features, check, reports, native).to_string()
    });
    table("maintenance", |[reports, native]| {
        format!("{:?}", match retention(reports, native) {
            Retention::None => "",
            Retention::Reports => "reports",
            Retention::Native => "native",
            Retention::Both => "both",
        })
    });
    table("include_tool", |[feature, report, native]| {
        include_tool(feature, report, native).to_string()
    });
    table("repository", |[pr, supplied, valid]| accepts_repository(pr, supplied, valid).to_string());
    table("channel", |[allow_pin, pinned, named, exact]| {
        accepts_channel(allow_pin, pinned, named, exact).to_string()
    });
    table("override", |[selected, organization, valid]| {
        accepts_override(selected, organization, valid).to_string()
    });
    table("use_override", |[has_override]| effective_channel(has_override).to_string());
}
